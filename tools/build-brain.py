def load(path):
    rows = json.loads(gzip.open(path, "rb").read().decode("utf-8"))["messages"]
    out = []
    for r in rows:
        role, ts, content = r[0], r[1], re.sub(r"\s+", " ", str(r[2] or "")).strip()
        if not content or content.startswith("["):
            continue
        if SPAM.search(content):          # пересланные уведомления и мусор — не воспоминания
            continue
        if ts >= CUTOFF:                  # расставание — не её воспоминание
            continue
        out.append((role, ts, content))
    return out


def words(text):
    return [w for w in re.findall(r"[а-яёa-z]{3,}", text.lower()) if w not in STOP]


def salience(text):
    """Насколько сообщение «событийное» — по нему стоит вспоминать."""
    n = len(text.split())
    if n < 4 or n > 26:
        return 0.0
    score = 1.0 + (min(n, 16) - 4) * 0.22
    if re.search(r"\b(люблю|скучаю|прости|обидел|поссор|приеду|подар|болею|устал|боюсь|хочу сказать|важно|навсегда|расстат)\w*", text, re.I):
        score += 2.2
    if re.search(r"[❤💋🫶🥰😭😢🙄]", text):
        score += 0.4
    if re.search(r"^(да|нет|ну|не|а|и|ты|я)\s*$", text, re.I):
        score = 0.0
    return score


